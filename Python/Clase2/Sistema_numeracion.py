# Profundizando los sistemas de numeración

# Sistema decimal
a = 10
print(f"a decimal: {a}")

# Sistema binario
a= 0b1010
print(f"a binario: {a}")

# Sistema octal
a= 0o12
print(f"a octal: {a}")

# Sistema hexadecimal
a= 0xA
print(f"a hexadecimal: {a}")

