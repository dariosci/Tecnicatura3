# Conversion

# Base decimal
a = int('23', 10) # int('valor', base)
print(f"a= base decimal: {a}")

# Base binario
a = int('10111', 2) # int('valor', base)
print(f"a= base binario: {a}")

# Base octal
a = int('27', 8) # int('valor', base)
print(f"a= base octal: {a}")

# Base hexadecimal
a = int('17', 16) # int('valor', base)
print(f"a= base hexa: {a}")

# Base 5 sus valores son de 0 a 4
a = int('344', 5) # int('valor', base)
print(f"a= base 5: {a}")